// a*b/c with a 64-bit intermediate, without libgcc's 64-bit division
// (900 bytes of it). The product is one umull; the divide is a 32-step
// shift-and-subtract, on the assumption - true everywhere it is used -
// that the result fits in 32 bits.
int32_t wr_muldiv(int32_t a, int32_t b, int32_t c) {
  bool neg = ((a < 0) ^ (b < 0)) ^ (c < 0);
  uint32_t ua = (uint32_t)(a < 0 ? -a : a), ub = (uint32_t)(b < 0 ? -b : b);
  uint32_t d = (uint32_t)(c < 0 ? -c : c);
  if (!d) return 0;
  uint64_t n = (uint64_t)ua * ub;
  uint32_t hi = (uint32_t)(n >> 32), lo = (uint32_t)n;
  uint32_t q = 0, r = hi % d;
  for (int i = 31; i >= 0; i--) {
    r = (r << 1) | ((lo >> i) & 1u);
    if (r >= d) { r -= d; q |= 1u << i; }
  }
  return neg ? -(int32_t)q : (int32_t)q;
}

static uint32_t s_rng = 0x1a2b3c4du;

void wr_seed(uint32_t s) { s_rng = s ? s : 0x1a2b3c4du; }

uint32_t wr_rand(void) {
  s_rng ^= s_rng << 13;
  s_rng ^= s_rng >> 17;
  s_rng ^= s_rng << 5;
  return s_rng;
}
